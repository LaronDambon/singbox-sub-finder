"""Внутренний браузер проекта: логин один раз, проверки — из-под сессии.

Зачем это нужно
---------------
Часть сервисов показывает свою доступность ТОЛЬКО авторизованному
пользователю. Проверено на Gemini: анонимный HTTP-запрос всегда получает
лендинг с маркером BardChatUi и НИКОГДА — заглушку «Gemini пока не
поддерживается в вашей стране»; она рендерится клиентски после входа.
Поэтому обычная проверка через requests физически слепа к такой блокировке,
и в конфиг попадают серверы, которые у пользователя не работают.

Как устроено
------------
Каждый сервис получает СВОЙ профиль Chromium в отдельной папке:

    <BROWSER_SESSIONS_DIR>/<service>/profile/   <- живые cookies и localStorage

Логин выполняется один раз вручную (browser.login), дальше проверки идут
через тот же профиль и видят ровно то, что видит человек.

Безопасность
------------
1. Папка сессий по умолчанию ЛЕЖИТ ВНЕ РЕПОЗИТОРИЯ (см. paths.py), поэтому
   ни git add -A, ни клонирование репозитория её не задевают.
2. Значения cookies и паролей НИКОГДА не логируются и не печатаются:
   в лог попадают только имена и количество (см. redact.py).
3. Экспорт сессии (.enc) шифруется мастер-паролем (scrypt + Fernet),
   чтобы переносимый файл был бесполезен без пароля.
"""
